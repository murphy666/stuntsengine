static void
track_editor_copy_window_bitmap(struct SPRITE *dst, const struct SPRITE *src) {
    size_t bitmap_bytes;

    if (dst == 0 || src == 0 || dst->sprite_bitmapptr == 0 || src->sprite_bitmapptr == 0) {
        return;
    }

    bitmap_bytes = (size_t)src->sprite_pitch * (size_t)src->sprite_height;
    memcpy((unsigned char *)dst->sprite_bitmapptr, (unsigned char *)src->sprite_bitmapptr,
           bitmap_bytes);
}

